async function readText(path) {
  return readFile(join(repoRoot, path), "utf8");
}

function documentFromFile(path, raw) {
  const name = basename(path);
  const title = titleForPath(path);
  return normalizeDocument({
    id: `memory_lwt_internal_${slug(path)}_20260710`,
    sourceType: sourceTypeForPath(path),
    title,
    summary: summaryForPath(path, raw),
    content: `Source file: ${path}\n\n${raw}`,
    metadata: {
      sourceBatch: "2026-07-10",
      sourcePath: path,
      filename: name,
      generatedBy: "generate-super-agent-memory-sql"
    },
    relatedProducts: relatedProductsForText(raw),
    relatedCollections: relatedCollectionsForText(raw),
    relatedCampaigns: [],
    evidenceLinks: [path],
    sensitivity: "internal"
  });
}

function normalizeDocument(input) {
  return {
    id: sanitizeText(input.id, 240),
    sourceType: input.sourceType ?? "business_note",
    title: sanitizeText(input.title, 240),
    summary: sanitizeText(input.summary, 1000),
    content: sanitizeText(input.content, 8000),
    metadata: input.metadata ?? {},
    relatedProducts: sanitizeList(input.relatedProducts ?? []),
    relatedCollections: sanitizeList(input.relatedCollections ?? []),
    relatedCampaigns: sanitizeList(input.relatedCampaigns ?? []),
    evidenceLinks: sanitizeList(input.evidenceLinks ?? []),
    sensitivity: input.sensitivity ?? "internal"
  };
}

function upsertDocumentSql(document) {
  const chunks = splitMemoryChunks([document.title, document.summary, document.content].join("\n"));
  const insertDoc = `insert into agent_memory_documents (
  id, source_type, title, summary, content, metadata, related_products,
  related_collections, related_campaigns, evidence_links, sensitivity, updated_at
)
values (
  ${sqlString(document.id)},
  ${sqlString(document.sourceType)},
  ${sqlString(document.title)},
  ${sqlString(document.summary)},
  ${sqlString(document.content)},
  ${sqlJson(document.metadata)},
  ${sqlTextArray(document.relatedProducts)},
  ${sqlTextArray(document.relatedCollections)},
  ${sqlTextArray(document.relatedCampaigns)},
  ${sqlJson(document.evidenceLinks)},
  ${sqlString(document.sensitivity)},
  now()
)
on conflict (id) do update set
  source_type = excluded.source_type,
  title = excluded.title,
  summary = excluded.summary,
  content = excluded.content,
  metadata = excluded.metadata,
  related_products = excluded.related_products,
  related_collections = excluded.related_collections,
  related_campaigns = excluded.related_campaigns,
  evidence_links = excluded.evidence_links,
  sensitivity = excluded.sensitivity,
  updated_at = now();`;

  const deleteChunks = `delete from agent_memory_chunks where document_id = ${sqlString(document.id)};`;
  const insertChunks = chunks.length
    ? `insert into agent_memory_chunks (id, document_id, chunk_index, content, embedding, embedding_model)
values
${chunks.map((chunk, index) => `  (${sqlString(`${document.id}_chunk_${index}`)}, ${sqlString(document.id)}, ${index}, ${sqlString(chunk)}, null, null)`).join(",\n")};`
    : "-- No chunks generated.";
  return [insertDoc, deleteChunks, insertChunks];
}

function sourceTypeForPath(path) {
  if (path.includes("shopper-behavior")) return "market_signal";
  if (path.includes("content")) return "business_note";
  if (path.endsWith(".json")) return "business_note";
  return "business_note";
}

function titleForPath(path) {
  if (path === "README.md") return "Supplier Ops Agent README";
  return path
    .replace(/^docs\//, "")
    .replace(/^config\//, "Config: ")
    .replace(/^imports\/shopper-behavior\//, "Shopper Behavior Sample: ")
    .replace(/\.md$|\.json$|\.csv$/g, "")
    .replace(/[_-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function summaryForPath(path, raw) {
  if (path.includes("sample-")) {
    return `Aggregate sample report used to seed LWT shopper behavior and market-signal retrieval memory: ${path}.`;
  }
  if (path.includes("content-radar")) {
    return "Content radar source settings and approved topic clusters for LWT market listening.";
  }
  if (path.includes("LWT_INTELLIGENCE_CENTER")) {
    return `Internal implementation and operating documentation for the LWT Intelligence Center: ${path}.`;
  }
  return sanitizeText(raw.split(/\r?\n/).find((line) => line.trim()) ?? path, 400);
}

function relatedProductsForText(value) {
  const products = [];
  if (/magnesium/i.test(value)) products.push("Magnesium Glycinate");
  if (/sleep/i.test(value)) products.push("Sleep Support Formula");
  return products;
}

function relatedCollectionsForText(value) {
  const collections = [];
  if (/magnesium/i.test(value)) collections.push("Magnesium");
  if (/sleep/i.test(value)) collections.push("Sleep Support");
  if (/gut|probiotic|histamine/i.test(value)) collections.push("Gut Health");
  if (/immune|vitamin d/i.test(value)) collections.push("Immune Support");
  if (/stress/i.test(value)) collections.push("Stress Support");
  return [...new Set(collections)];
}

function sanitizeText(value, maxChars = 8000) {
  const redacted = String(value)
    .replace(/[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}/gi, "[redacted-email]")
    .replace(/(?:\+?1[-.\s]?)?(?:\(?\d{3}\)?[-.\s]?)\d{3}[-.\s]?\d{4}/g, "[redacted-phone]")
    .replace(/\s+/g, " ")
    .trim();
  if (redacted.length <= maxChars) return redacted;
  return `${redacted.slice(0, Math.max(0, maxChars - 14)).trimEnd()} [truncated]`;
}

function sanitizeList(values) {
  return values.map((value) => sanitizeText(value, 500)).filter(Boolean);
}

function splitMemoryChunks(content, maxChunkChars = 1200) {
  const normalized = content.replace(/\s+/g, " ").trim();
  if (!normalized) return [];
  const chunks = [];
  let remaining = normalized;
  while (remaining.length > maxChunkChars) {
    const splitAt = findSplitPoint(remaining, maxChunkChars);
    chunks.push(remaining.slice(0, splitAt).trim());
    remaining = remaining.slice(splitAt).trim();
  }
  if (remaining) chunks.push(remaining);
  return chunks.slice(0, 25);
}

function findSplitPoint(value, maxChunkChars) {
  const window = value.slice(0, maxChunkChars);
  const sentence = Math.max(window.lastIndexOf(". "), window.lastIndexOf("? "), window.lastIndexOf("! "));
  if (sentence > maxChunkChars * 0.5) return sentence + 1;
  const space = window.lastIndexOf(" ");
  return space > maxChunkChars * 0.5 ? space : maxChunkChars;
}

function slug(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "").slice(0, 120);
}

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlJson(value) {
  return `${sqlString(JSON.stringify(value))}::jsonb`;
}

function sqlTextArray(values) {
  if (!values.length) return "array[]::text[]";
  return `array[${values.map(sqlString).join(", ")}]::text[]`;
}
